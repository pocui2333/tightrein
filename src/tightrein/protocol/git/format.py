"""分支名、提交信息、PR 标题与描述的格式(protocol/git.md)，纯函数加一次只读的约定识别。

格式怎么确定(每项记下来源)：
1. settings 中缺省层之上(本机或工作区)写明的 `git.branch`、`git.commit`、`git.prTemplate`(接入时经确认的历史推断也写在这里)；
2. 项目仓库写明的约定：PR 模板文件；commitlint 继承 config-conventional；CONTRIBUTING、AGENTS、CLAUDE.md 中
   同一行写了分支(或提交)并在反引号中给出带占位符的模板，占位符全部认得出、全部文档只有一个不同模板时才采用；
3. 通用格式(settings/defaults.json 的 `git` 段)。
从历史推断(infer)只给出结果交接入时确认，不自动采用。

格式串的占位符：分支 `{prefix}`(个人前缀，带结尾的 /，没有时为空)、`{type}`、`{issue}`(不补零的编号)、`{slug}`；
提交 `{type}`、`{scope}`(带括号，没有范围时为空)、`{summary}`；PR 标题 `{type}`、`{summary}`。
不带 AI 署名：提交信息完全由程序按格式串拼出，不加 Co-Authored-By、Generated with 之类的行；个人前缀不能是 AI 或工具名。
"""

